def manage_mfa(
    action: str = "",
    language: str = "",
) -> dict[str, Any]:
    """Turns two-step verification (MFA) on or off. Use only after the caller has passed
      login. Turning it off first returns STEP_UP_REQUIRED: send an email code with
      send_login_code channel email, check it, then call again.

    Args:
      action: enable or disable.
      language: Active language code (en-US or fr-CA).

    Returns:
      status, data (mfa_enabled, method, destination_last4, effective_display,
        spoken_summary), error_message, tracking_id. Errors add error (NOT_LOGGED_IN,
        STEP_UP_REQUIRED, ALREADY_APPLIED, INVALID_INPUT) and agent_action.
    """
    ctx = globals().get("context")
    state = getattr(ctx, "state", None) if ctx is not None else None
    if state is None and isinstance(ctx, dict):
        state = ctx
    return manage_mfa_impl(
        action=action,
        language=language,
        state=state,
    )


